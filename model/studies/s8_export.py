"""S8: export the design into the firmware and its tests.

1. fw/lib/fq/src/fq_data.c: probe layout and calibration of both tanks, the attitude table,
   chi-square thresholds, r_nom and the monitor limit (from S5);
2. fw/tests/unit/vectors.h: back-to-back vectors - inputs and the reference results of
   gauge.solve / gauge.monitor - which the C unit tests must reproduce;
3. fw/sim/scenarios/*.csv: 10 Hz acquisition data for the Renode tests (flight profile, probe
   faults, low fuel, compensator drift, stuck low-level sensor), with the true masses.
"""

from __future__ import annotations

import json

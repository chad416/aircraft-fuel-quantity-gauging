import os

import numpy as np

from common import RES, ROOT, dump
from fqsim import data, design, fuel, gauge, probe, tank

FW = os.path.join(ROOT, "fw")


def f32(v):
    s = "%.9g" % float(v)
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def mon_tol_pct():
    with open(os.path.join(RES, "s5_fde.json"), encoding="utf-8") as f:
        return float(json.load(f)["mon_tol_pct_fs"])


def write_data():
    t = design.the_tank()
    tb = design.the_table()
    probes = design.chosen_probes()
    fs = gauge.full_scale_mass(t)
    tol = mon_tol_pct() / 100.0 * fs
    out = []
    out.append("/*\n * GENERATED by model/studies/s8_export.py - do not edit.\n")
    out.append(" * Probe layout (S3), attitude table, thresholds and monitor limit (S5).\n")
    out.append(' * SPDX-License-Identifier: MIT\n */\n#include "fq/fq.h"\n\n')
    out.append("const float fq_r_nom = %s;\n\n" % f32(fuel.R_NOM))
    out.append("const float fq_chi2[FQ_NP] = {%s};\n\n" % ", ".join(f32(v) for v in gauge.CHI2))
    out.append("const fq_tank_cfg_t fq_tank_cfg[FQ_NT] = {\n")
    kl = data.PROBE_K * data.COMP_LEN * 1e12
    cd = (data.PROBE_C_END + data.PROBE_K * data.COMP_LEN) * 1e12
    for mirror in (True, False):
        out.append("\t{\n\t\t{\n")
        for p in probes:
            out.append(
                "\t\t\t{%s, %s, %s, %s, %s, %s},\n"
                % (f32(p.x), f32(p.y), f32(p.z_bot), f32(p.length), f32(p.c_dry * 1e12), f32(p.k * 1e12))
            )
        out.append("\t\t},\n")
        out.append(
            "\t\t%s, %s, %s, %s, %s, %s, %s, %s,\n\t},\n"
            % (
                f32(cd),
                f32(kl),
                f32(tb.xr),
                f32(tb.yr),
                f32(tb.v_unusable),
                f32(fs),
                f32(tol),
                "true" if mirror else "false",
            )
        )
    out.append("};\n\n")

    def arr2(name, a):
        out.append("const float %s[FQ_NSX][FQ_NSY] = {\n" % name)
        for row in a:
            out.append("\t{%s},\n" % ", ".join(f32(v) for v in row))
        out.append("};\n\n")

    arr2("fq_zempty", tb.z_empty)
    arr2("fq_zfull", tb.z_full)
    out.append("const float fq_vol[FQ_NSX][FQ_NSY][FQ_NU] = {\n")
    for plane in tb.vol:
        out.append("\t{\n")
        for row in plane:
            out.append("\t\t{%s},\n" % ", ".join(f32(v) for v in row))
        out.append("\t},\n")
    out.append("};\n")
    with open(os.path.join(FW, "lib", "fq", "src", "fq_data.c"), "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    return fs, tol


def vectors(rng, n=160):
    """Back-to-back cases: healthy, faulted, fallback and invalid states of the right tank."""
    t = design.the_tank()
    probes = design.chosen_probes()
    cfg = design.cfg_for()
    cases = []
    kinds = (
        ["healthy"] * 70 + ["bias"] * 30 + ["open"] * 10 + ["water"] * 10 + ["nosf"] * 10 + ["failed"] * 10
    )
    kinds += ["noeps"] * 10 + ["dens"] * 10
    for kind in kinds[:n]:
        f = fuel.random_fuel(rng)
        tx, ty = rng.uniform(*data.TILT_X_DEG), rng.uniform(*data.TILT_Y_DEG)
        sx, sy = tank.slopes(tx, ty)
        u = rng.uniform(0.02, 1.0)
        z = t.z_empty(sx, sy) + u * (t.z_full(sx, sy) - t.z_empty(sx, sy))
        st = probe.TankState(z, sx, sy, f, rng.uniform(-40, 50), rng.uniform(0, 10))
        caps, cc = probe.measure(t, probes, st, probe.draw_errors(rng, len(probes)))
        caps = list(caps * 1e12)
        cc *= 1e12
        j = int(rng.integers(0, len(probes)))
        if kind == "bias":
            caps[j] += cfg.k_pf[j] * 1.1 * rng.uniform(-0.06, 0.06)
        elif kind == "open":
            caps[j] = 0.5
        elif kind == "water":
            caps[j] += cfg.k_pf[j] * 77.0 * 0.004
        eps = gauge.comp_eps(cfg, cc)
        eps_ok = eps is not None
        if kind == "noeps" or not eps_ok:
            eps, eps_ok = gauge.EPS_DEFAULT, False
        sfv = kind != "nosf"
        sf = (-sx * 0.98, -sy * 0.98, 0.98)
        failed = (1 << j) if kind == "failed" else 0
        hold = (sx, sy) if kind == "nosf" and rng.uniform() < 0.5 else None
        rho = float(probe.true_mean_rho(t, st)) if kind == "dens" else None
        r = solve_eps(cfg, caps, eps, eps_ok, sf if sfv else None, rho, failed, hold)
        mv = gauge.monitor(
            cfg, caps, eps, sf if sfv else None, [bool(failed >> i & 1) for i in range(len(probes))]
        )
        cases.append((caps, eps, eps_ok, sfv, sf, rho, failed, hold, r, mv))
    return cases


def solve_eps(cfg, caps, eps, eps_ok, sf, rho, failed, hold):
    """gauge.solve with a given eps (what the C core receives) instead of the compensator."""
    c_comp = cfg.comp_cdry_pf + cfg.comp_kl_pf * (eps - 1.0)
    fl = [bool(failed >> i & 1) for i in range(len(caps))]
    if eps_ok:
        return gauge.solve(cfg, caps, c_comp, sf=sf, rho_meas=rho, failed=fl, hold=hold)
    return gauge.solve(cfg, caps, 0.0, sf=sf, rho_meas=rho, eps_hint=eps, failed=fl, hold=hold)


def write_vectors(cases):
    o = ["/* GENERATED by model/studies/s8_export.py - do not edit. Back-to-back vectors:\n"]
    o.append(" * model/fqsim/gauge.py results for the right tank. SPDX-License-Identifier: MIT */\n")
    o.append("#ifndef FQ_VECTORS_H\n#define FQ_VECTORS_H\n\n")
    o.append(
        "typedef struct {\n\tfloat caps[8];\n\tfloat eps;\n\tint eps_ok;\n\tint sf_valid;\n\tfloat sf[3];\n"
    )
    o.append("\tint rho_valid;\n\tfloat rho;\n\tint failed;\n\tint hold_valid;\n\tfloat hold[2];\n")
    o.append("\tint status;\n\tfloat z_ref;\n\tfloat sx;\n\tfloat sy;\n\tfloat volume;\n\tfloat mass;\n")
    o.append(
        "\tint excluded;\n\tint n_live;\n\tint fallback;\n\tint mon_ok;\n\tfloat mon_usable;\n} vec_t;\n\n"
    )
    o.append("#define N_VEC %d\n\nstatic const vec_t vec[N_VEC] = {\n" % len(cases))
    for caps, eps, eps_ok, sfv, sf, rho, failed, hold, r, mv in cases:
        o.append(
            "\t{{%s}, %s, %d, %d, {%s}, %d, %s, %d, %d, {%s}, %d, %s, %s, %s, %s, %s, %d, %d, %d, %d, %s},\n"
            % (
                ", ".join(f32(c) for c in caps),
                f32(eps),
                int(eps_ok),
                int(sfv),
                ", ".join(f32(v) for v in sf),
                int(rho is not None),
                f32(rho if rho is not None else 0.0),
                failed,
                int(hold is not None),
                ", ".join(f32(v) for v in (hold if hold is not None else (0.0, 0.0))),
                r.status,
                f32(r.z_ref),
                f32(r.sx),
                f32(r.sy),
                f32(r.volume),
                f32(r.mass),
                r.excluded,
                r.n_live,
                int(r.fallback),
                int(mv is not None),
                f32(mv if mv is not None else 0.0),
            )
        )
    o.append("};\n\n#endif\n")
    with open(os.path.join(FW, "tests", "unit", "vectors.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(o))


# ---- Renode scenarios -----------------------------------------------------------------------

COLS = (
    ["t"]
    + ["cL%d" % i for i in range(1, 9)]
    + ["cR%d" % i for i in range(1, 9)]
    + ["compL", "compR", "fx", "fy", "fz", "sf", "wetL", "wetR", "rhoL", "rhoR", "mL", "mR", "send"]
)


def scenario(rng, profile, faults=None, wet_override=None, comp_drift=None, gap=None):
    """profile(t) -> (tilt_x, tilt_y, mass_L, mass_R, fuel temperature); 10 Hz rows."""
    t_ = design.the_tank()
    probes = design.chosen_probes()
    f = fuel.Fuel(r=fuel.R_NOM * 1.004, rho15=802.0)  # a fuel slightly off the nominal r (A)
    errs = [probe.draw_errors(rng, len(probes)), probe.draw_errors(rng, len(probes))]
    rows = []
    steps = int(round(profile.duration * 10))
    zc = [None, None]
    for k in range(steps):
        tt = k * 0.1
        tx, ty, mL, mR, temp = profile(tt)
        row = [round(tt, 1)]
        caps_all, comps, truth = [], [], []
        for side, m in enumerate((mL, mR)):
            sy_body = math.tan(math.radians(ty))
            sx = math.tan(math.radians(tx))
            sy = -sy_body if side == 0 else sy_body
            rho = float(f.rho(temp))
            v = m / rho + t_.v_unusable
            # bisection on the plane height, warm-started from the previous row
            lo, hi = t_.z_empty(sx, sy), t_.z_full(sx, sy)
            if zc[side] is not None:
                lo2, hi2 = zc[side] - 0.02, zc[side] + 0.02
                if t_.volume_below(lo2, sx, sy) < v < t_.volume_below(hi2, sx, sy):
                    lo, hi = lo2, hi2
            for _ in range(30):
                mid = 0.5 * (lo + hi)
                if t_.volume_below(mid, sx, sy) < v:
                    lo = mid
                else:
                    hi = mid
            z = 0.5 * (lo + hi)
            zc[side] = z
            st = probe.TankState(z, sx, sy, f, temp, 0.0)
            water = None
            if faults:
                water = [0.0] * len(probes)
            caps, cc = probe.measure(t_, probes, st, errs[side], water)
            caps = list(caps * 1e12)
            cc *= 1e12
            if faults:
                for fs_side, idx, t0, kind, size in faults:
                    if fs_side == side and tt >= t0:
                        if kind == "open":
                            caps[idx] = 0.4
                        elif kind == "bias":
                            caps[idx] += probes[idx].k * 1e12 * (float(f.eps(temp)) - 1.0) * size
                        elif kind == "water":
                            caps[idx] += probes[idx].k * 1e12 * (data.WATER_EPS - float(f.eps(temp))) * size
            if comp_drift and comp_drift[0] == side and tt >= comp_drift[1]:
                cc += data.PROBE_K * data.COMP_LEN * 1e12 * comp_drift[2]  # eps error x k L (pF)
            caps_all += caps
            comps.append(cc)
            truth.append(m)
        fx = -math.sin(math.radians(tx))
        fz = math.cos(math.radians(tx))
        fy = -math.tan(math.radians(ty)) * fz
        wet = [truth[0] > 60.0, truth[1] > 60.0]
        if wet_override is not None:
            wet = wet_override(tt, wet)
        send = 0 if (gap is not None and gap[0] <= tt < gap[1]) else 1
        row += [round(c, 2) for c in caps_all] + [round(c, 2) for c in comps]
        row += [round(fx, 4), round(fy, 4), round(fz, 4), 1, int(wet[0]), int(wet[1]), 0.0, 0.0]
        row += [round(truth[0], 2), round(truth[1], 2), send]
        rows.append(row)
    return rows


def write_csv(name, rows):
    path = os.path.join(FW, "sim", "scenarios", name)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(",".join(COLS) + "\n")
        for r in rows:
            f.write(",".join(str(v) for v in r) + "\n")
    return path


class Profile:
    def __init__(self, fn, duration):
        self.fn = fn
        self.duration = duration

    def __call__(self, t):
        return self.fn(t)


def flight(t):
    """Ground, take-off roll + rotation, climb, cruise with turns and a sideslip, descent.
    Burn 0.2 kg/s per tank (about 5x real: keeps the run short) (A)."""
    if t < 5:
        tx = 0.0
    elif t < 30:
        a = 0.25 - 0.12 * (t - 5) / 25
        pitch = 0.0 if t < 25 else min((t - 25) * 4.0, 10.0)
        th = math.radians(pitch)
        tx = math.degrees(math.atan((a + math.sin(th)) / math.cos(th)))
    elif t < 60:
        tx = 8.0
    elif t < 100:
        tx = 2.0
    else:
        tx = -3.0
    ty = 3.0 if 75 <= t < 85 else 0.0
    burn = 0.0 if t < 5 else 0.2 * (t - 5)
    return tx, ty, 420.0 - burn, 400.0 - burn, 5.0


def cruise(t):
    return 2.0, 0.0, 350.0 - 0.05 * t, 352.0 - 0.05 * t, -10.0


def low(t):
    return 1.0, 0.0, 85.0 - 0.6 * t, 95.0 - 0.6 * t, 0.0


def main():
    rng = np.random.default_rng(8)
    fs, tol = write_data()
    cases = vectors(rng)
    write_vectors(cases)
    sc = {}
    sc["sc1_flight.csv"] = scenario(rng, Profile(flight, 120.0))
    sc["sc2_faults.csv"] = scenario(
        rng,
        Profile(cruise, 40.0),
        faults=[(1, 2, 10.0, "open", 0.0), (1, 4, 20.0, "bias", 0.030), (0, 1, 30.0, "water", 0.003)],
    )
    sc["sc3_low.csv"] = scenario(rng, Profile(low, 70.0))
    sc["sc4_comp_gap.csv"] = scenario(rng, Profile(cruise, 30.0), comp_drift=(1, 5.0, 0.06), gap=(15.0, 17.0))
    sc["sc5_stuck_dry.csv"] = scenario(
        rng, Profile(cruise, 75.0), wet_override=lambda tt, w: [w[0], tt < 5.0]
    )
    for k, rows in sc.items():
        write_csv(k, rows)
    stat = {
        "fs_tank_kg": fs,
        "mon_tol_kg": tol,
        "vectors": len(cases),
        "vector_status": {s: sum(1 for c in cases if c[8].status == s) for s in (0, 1, 2)},
        "scenarios": {k: len(v) for k, v in sc.items()},
    }
    print(stat)
    dump("s8_export.json", stat)


if __name__ == "__main__":
    main()
